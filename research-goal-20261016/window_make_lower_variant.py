"""Reproducibly freeze a lower-floor backup without mutating the active search."""
from pathlib import Path
import hashlib,json
HERE=Path(__file__).resolve().parent
source=HERE/'window_global_cover.py'
target=HERE/'window_lower_global_cover.py'
text=source.read_text(encoding='utf8')
changes={
    'g.TARGET=221*(g.DEN//25000)':'g.TARGET=11*(g.DEN//1250)',
    'cn=88400000':'cn=88000000',
    "default=HERE/'window-global-cover.json'":"default=HERE/'window-lower-global-cover.json'",
    "'target':'221/25000'":"'target':'11/1250'",
}
for old,new in changes.items():
    assert text.count(old)==1,old
    text=text.replace(old,new)
prefix='# Reproducibly generated by window_make_lower_variant.py; c=0.0088 backup.\n'
raw=(prefix+text).encode('utf8')
target.write_bytes(raw)
out={'scope':__doc__,'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
     'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
     'generated_sha256':hashlib.sha256(raw).hexdigest(),'substitutions':changes,
     'floor':'11/1250','global_floor_Lean_proven':False,'new_zero_proportion_proven':False}
Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n',encoding='utf8')
print(json.dumps(out))
