"""Build the 15 October upload from the separately verified proof modules."""
from pathlib import Path
import hashlib
import json
import re
from fractions import Fraction
from bundle_gram_defect_solution import strip_imports, remaining_sections, code_mask

ROOT = Path(__file__).resolve().parents[1]
NAMES = ["Core", "SharpWindow", "RefinedCounting", "Final"]


def main():
    imports = {"ChallengeDeps", "ChallengeDeps.CandidateSpec"}
    payloads, source_hashes = [], {}
    for i, name in enumerate(NAMES):
        path = ROOT / "GramDefect20261015" / (name + ".lean")
        raw = path.read_bytes()
        source = raw.decode("utf8")
        body, found = strip_imports(source)
        imports.update(found)
        close = remaining_sections(body)
        section = f"Record20261015Bundle_{i}"
        payloads.append(f"/- Source: GramDefect20261015/{name}.lean -/\nsection {section}\n"
                        + body + "\n" + "end\n" * close + f"end {section}\n")
        source_hashes[str(path.relative_to(ROOT)).replace("\\", "/")] = hashlib.sha256(raw).hexdigest()
    imports = sorted(x for x in imports if not x.startswith("GramDefect20261015."))
    final = (ROOT / "GramDefect20261015/Final.lean").read_text(encoding="utf8")
    match = re.search(r"^def recordRatio : ℝ := (\d+) / (\d+)$", final, re.M)
    if not match:
        raise ValueError("Final.lean does not give an explicit exact score")
    p, q = map(int, match.groups())
    assert Fraction(p, q).denominator == q
    wrapper = """
noncomputable section
namespace Record20261015SubmissionCounts
theorem count_eq (a b : ℝ) : _root_.Ncount a b = Zeta23.Ncount a b := by rfl
theorem distinct_eq (a b : ℝ) : _root_.N0star a b = Zeta23.N0star a b := by rfl
end Record20261015SubmissionCounts

theorem candidate_strict_improvement : currentRecordKappa < candidateKappa := by
  norm_num [currentRecordKappa, candidateKappa]

theorem candidate_critical_line_bound :
    ∀ ε > 0, ∃ T₀ : ℝ, ∀ T ≥ T₀,
      (candidateKappa - ε) * (Ncount T (2 * T) : ℝ) ≤ N0star T (2 * T) := by
  simpa only [candidateKappa, GramDefect20261015.recordRatio,
    Record20261015SubmissionCounts.count_eq, Record20261015SubmissionCounts.distinct_eq]
    using GramDefect20261015.distinct_dyadic

theorem candidate_critical_line_bound_cumulative :
    ∀ ε > 0, ∃ T₀ : ℝ, ∀ T ≥ T₀,
      (candidateKappa - ε) * (Ncount 0 T : ℝ) ≤ N0star 0 T := by
  simpa only [candidateKappa, GramDefect20261015.recordRatio,
    Record20261015SubmissionCounts.count_eq, Record20261015SubmissionCounts.distinct_eq]
    using GramDefect20261015.distinct_cumulative
end
"""
    header = """/-
Copyright (c) 2026 Li Xiang (lixiang90), modifications. Apache-2.0.
Modified 2026-10-15: raise the local floor proved by the accepted ajp88
nine-point certificate tree and sharpen the AM window enclosure.
All inherited source/license notices are retained. Generated by
scripts/bundle_record_20261015.py. Only pinned trusted package imports
are needed; no repository proof module or candidate-defined axiom is used.
The website generates candidateKappa and currentRecordKappa.
-/
"""
    source = header + "\n".join("import " + i for i in imports) + "\n" + "\n".join(payloads) + wrapper
    mask = code_mask(source)
    for name in ["candidate_strict_improvement", "candidate_critical_line_bound", "candidate_critical_line_bound_cumulative"]:
        assert len(re.findall(r"^theorem " + name + r"\s*:", mask, re.M)) == 1
    assert not re.search(r"\b(?:sorry|admit|axiom|native_decide|unsafe)\b", mask)
    assert not re.search(r"^\s*(?:def|abbrev|opaque)\s+(?:candidateKappa|currentRecordKappa)\b", mask, re.M)
    assert remaining_sections(source) == 0
    raw = source.encode("utf8")
    assert len(raw) <= 2_000_000, len(raw)
    dest = ROOT / "submission/gram-defect-20261015"
    (dest / "proof").mkdir(parents=True, exist_ok=True)
    (dest / "proof/Solution.lean").write_bytes(raw)
    report = {"numerator": str(p), "denominator": str(q), "source_bytes": len(raw),
              "source_sha256": hashlib.sha256(raw).hexdigest(), "source_modules": source_hashes,
              "source_size_limit": 2_000_000, "remaining_bytes": 2_000_000-len(raw),
              "imports": imports, "submitted": False, "official_website_acceptance": False}
    (dest / "manifest.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf8", newline="\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
